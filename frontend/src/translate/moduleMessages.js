export const moduleMessagesByLang = { pt, en, es, ar };

export function mergeModuleMessages(messages) {
  const merged = { ...messages };
  for (const [lang, modules] of Object.entries(moduleMessagesByLang)) {
    const bucket = merged[lang] || merged[lang === "pt" ? "pt-BR" : lang];
    if (!bucket?.translations) continue;
    bucket.translations.modules = modules;
    if (lang === "pt") {
      merged["pt-BR"] = merged["pt-BR"] || { translations: {} };
      merged["pt-BR"].translations = {
        ...merged["pt-BR"].translations,
        modules,
      };
    }
  }
  return merged;
}
